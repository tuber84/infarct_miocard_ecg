import { CaseId } from '../types';

/** Медицинская основа — сохранённые в ref/gudelines российские КР 2024 года. */
export const RUSSIAN_GUIDELINES = {
  stemi: {
    title: 'ИМпST — клинические рекомендации РФ, 2024',
    url: 'https://russjcardiol.elpub.ru/jour/article/view/6306',
  },
  nste: {
    title: 'ОКСбпST — клинические рекомендации РФ, 2024',
    url: 'https://russjcardiol.elpub.ru/jour/article/view/6319',
  },
} as const;

const STEMI_IDS: CaseId[] = [
  'lad_prox',
  'lad_mid',
  'lad_wrap',
  'd1',
  'rca_prox',
  'rca_dist',
  'pda',
  'lcx',
  'posterior',
  'lbbb_sgarbossa',
];
const NSTEMI_IDS: CaseId[] = ['nstemi_antlat', 'nstemi_inf', 'nstemi_tinv'];
const MIMIC_IDS: CaseId[] = ['lbbb_benign', 'pericarditis', 'early_repol', 'takotsubo'];

export function getClinicalGuidance(caseId: CaseId) {
  const isStemi = STEMI_IDS.includes(caseId);
  const isMimic = MIMIC_IDS.includes(caseId);
  const source = isStemi || isMimic ? RUSSIAN_GUIDELINES.stemi : RUSSIAN_GUIDELINES.nste;

  let timing: string;
  let context: string;

  if (isStemi) {
    timing =
      caseId === 'lbbb_sgarbossa'
        ? 'При подозрении на ОИМ на фоне БЛНПГ и симптомах <12 ч (при положительных критериях Сгарбосса / модифицированных критериях Смита, нестабильности гемодинамики) применяют тактику экстренной реперфузии (первичное ЧКВ при ожидаемом времени от диагноза до проводника ≤120 мин; цель в инвазивном центре ≤60 мин).'
        : 'При симптомах <12 ч первичное ЧКВ предпочтительно, если ожидаемое время от диагноза до проведения проводника ≤120 мин. Цель от диагноза до проводника: ≤60 мин в инвазивном центре, ≤90 мин при переводе из неинвазивного учреждения. Это сроки организации реперфузии, а не время допустимого ожидания.';
    context =
      caseId === 'lbbb_sgarbossa'
        ? 'Сочетание полной БЛНПГ и острой окклюзии ПМЖВ (LAD) задано условиями учебного примера. БЛНПГ затрудняет стандартную оценку ST/Q, поэтому опираются на критерии Сгарбосса/Смита, клинику и сравнение с архивной ЭКГ.'
        : 'Сосуд, кровоток и зона поражения заданы условиями учебного примера. При разборе пациента ЭКГ-паттерн сопоставляют с клиникой, динамикой и результатами КАГ.';
  } else if (caseId === 'normal') {
    timing =
      'Нормальная ЭКГ не исключает ОКС. При сохраняющемся подозрении нужны клиническая оценка, тропонин в динамике и повторная ЭКГ; при неинформативной записи — например, через 15–30 мин в первый час, а при изменении симптомов — повторная оценка.';
    context =
      'Здоровый человек и нормальное коронарное русло заданы условиями примера; одна нормальная ЭКГ этого не доказывает.';
  } else if (caseId === 'lbbb_benign') {
    timing =
      'Неосложнённая БЛНПГ без положительных критериев Сгарбосса/Смита сама по себе не означает острую коронарную окклюзию. При ангинозной боли сравнивают с архивной ЭКГ, оценивают динамику высокочувствительного тропонина, ЭхоКГ и при сохраняющемся подозрении решают вопрос о КАГ.';
    context =
      'Интактное коронарное русло и пропорциональная вторичная дискордантность ST–T заданы условиями примера. Новая или предположительно новая БЛНПГ при продолжающейся ишемии оценивается в общем клиническом контексте.';
  } else if (caseId === 'pericarditis') {
    timing =
      'При типичном остром перикардите коронарная реваскуляризация не требуется. Однако при наличии сомнений в природе боли в груди, локальности подъёма ST или высоком риске ИБС приоритет — исключение ОКС (тропонин, ЭхоКГ, при сомнениях — КАГ).';
    context =
      'Диффузное вогнутое смещение ST и отклонение сегмента PR без поражения коронарных артерий заданы условиями учебного примера.';
  } else if (caseId === 'early_repol') {
    timing =
      'Синдром ранней реполяризации желудочков (СРРЖ) — доброкачественный стабильный вариант ЭКГ и не требует экстренной КАГ при отсутствии клиники ОКС. При ангинозной боли необходимы серийные ЭКГ и тропонин в динамике.';
    context =
      'Вариант нормы (СРРЖ) без динамики и с проходимым коронарным руслом задан условиями примера.';
  } else if (caseId === 'takotsubo') {
    timing =
      'Синдром Такоцубо является диагнозом исключения: на догоспитальном и начальном госпитальном этапе пациента с элевацией ST ведут по алгоритму ИМпST до выполнения экстренной КАГ и подтверждения проходимости коронарных артерий.';
    context =
      'Стресс-индуцированное обратимое баллонирование верхушки ЛЖ при интактных коронарных артериях (TIMI 3) задано условиями примера; вентрикулография / ЭхоКГ выявляют акинезию за пределами бассейна одной артерии.';
  } else {
    timing =
      'При очень высоком риске — КАГ максимально рано, в первые 2 ч после госпитализации: рефрактерная боль, нестабильная гемодинамика, опасные аритмии, ишемическая ОСН, механические осложнения или повторные динамические изменения ST/T. При высоком риске (ИМбпST, преходящий ST↑, динамика ST/T, GRACE >140) — инвазивная стратегия в госпитализацию; ранняя КАГ <24 ч имеет класс IIa A. При внутрибольничном ОКС отсчёт — от обращения за помощью.';
    context = NSTEMI_IDS.includes(caseId)
      ? 'В этом учебном случае диагноз ИМбпST предполагает подтверждающую динамику тропонина и признаки ишемии. Сосуд, кровоток и зона повреждения заданы как пример. Отсутствие Q не является обязательным признаком ИМбпST.'
      : 'Сосуд, кровоток и зона поражения заданы условиями учебного примера. При разборе пациента ЭКГ-паттерн сопоставляют с клиникой, динамикой и результатами КАГ.';
  }

  return {
    source,
    timing,
    context,
    sections:
      isStemi || isMimic
        ? '§1.1, §2.4, §3.1.1; при вовлечении ПЖ — §3.2.1, §3.2.4 и §3.5'
        : '§1.1, §2.4, §3.1.1; приложение А3: изменения ЭКГ при окклюзирующем поражении КА',
  };
}

